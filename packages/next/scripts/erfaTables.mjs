// One-off developer tool: extracts the `static const` series tables of ERFA's
// dtdb.c, xy06.c and s06.c into TypeScript. Its output is committed; it is
// not part of the build.
//
// Usage: node scripts/erfaTables.mjs <erfa-src-dir>
//
// Each table is written flat, row-major, with the numbers' source spelling
// preserved so no precision is lost. Derived from ERFA; see
// src/time/erfa/LICENSE.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const srcDir = process.argv[2];
if (!srcDir) {
  console.error("usage: node scripts/erfaTables.mjs <erfa-src-dir>");
  process.exit(1);
}
const outDir = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "time",
  "erfa",
);

/** What each ERFA table holds, with its row layout. */
const DOCS = {
  fairhd:
    "Fairhead & Bretagnon TDB-TT series: 787 rows of [amplitude (s), frequency (rad per Julian millennium), phase (rad)]. Rows 0-473 are the T^0 terms, 474-678 T^1, 679-763 T^2, 764-783 T^3, 784-786 T^4.",
  xyp: "Polynomial coefficients (arcsec) of the CIP X (first 6) then Y (last 6) series, powers t^0 to t^5.",
  mfals:
    "Luni-solar fundamental-argument multipliers for the CIP X,Y series: rows of 5 integers for l, l', F, D, Om.",
  mfapl:
    "Planetary fundamental-argument multipliers for the CIP X,Y series: rows of 14 integers for l, l', F, D, Om, LMe, LVe, LE, LMa, LJu, LSa, LU, LNe, pA.",
  nc: "Pointers (1-based) into the amplitude array `a`, one per CIP X,Y frequency.",
  a: "Amplitude coefficients (microarcsec) of the CIP X,Y series, indexed through `nc`.",
  jaxy: "Per-series axis selector for the CIP X,Y amplitudes (0 = X, 1 = Y).",
  jasc: "Per-series sin/cos selector for the CIP X,Y amplitudes (0 = sine, 1 = cosine).",
  japt: "Per-series power-of-t selector for the CIP X,Y amplitudes.",
  sp: "Polynomial coefficients (arcsec) of the CIO locator s, powers t^0 to t^5.",
  s0: "CIO locator s terms of order t^0: rows of 10 numbers, 8 integer multipliers (l, l', F, D, Om, LVe, LE, pA) then the sine and cosine coefficients (arcsec).",
  s1: "CIO locator s terms of order t^1, same row layout as s0.",
  s2: "CIO locator s terms of order t^2, same row layout as s0.",
  s3: "CIO locator s terms of order t^3, same row layout as s0.",
  s4: "CIO locator s terms of order t^4, same row layout as s0.",
};

const FILES = [
  ["dtdb.c", "dtdbTable.ts", "eraDtdb (TDB-TT)"],
  ["xy06.c", "xy06Table.ts", "eraXy06 (CIP X, Y)"],
  ["s06.c", "s06Table.ts", "eraS06 (CIO locator s)"],
];

const NUMBER = /[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?/g;
const DECL =
  /static const (?:double|int|TERM)\s+(\w+)((?:\[[^\]]*\])+)\s*=\s*\{/g;

const counts = [];
for (const [cFile, tsFile, what] of FILES) {
  const src = readFileSync(join(srcDir, cFile), "utf8").replace(
    /\/\*[\s\S]*?\*\//g,
    "",
  );
  let out = `// Generated by scripts/erfaTables.mjs from ERFA v2.0.1 ${cFile}; do not edit.\n// Derived from ERFA, see ./LICENSE. Tables for ${what}.\n\n`;
  for (const m of src.matchAll(DECL)) {
    const name = m[1];
    // Walk braces from the opening one to its match.
    let depth = 1;
    let i = m.index + m[0].length;
    const start = i;
    while (depth > 0) {
      const ch = src[i++];
      if (ch === "{") {
        depth++;
      } else if (ch === "}") {
        depth--;
      }
    }
    const nums = src.slice(start, i - 1).match(NUMBER);
    if (!nums) {
      throw new Error(`${cFile}: empty table ${name}`);
    }
    if (!(name in DOCS)) {
      throw new Error(`${cFile}: undocumented table ${name}`);
    }
    out += `/** ${DOCS[name]} */\nexport const ${name}: readonly number[] = [\n${nums.join(",\n")},\n];\n\n`;
    counts.push(`${tsFile} ${name}: ${nums.length} numbers`);
  }
  writeFileSync(join(outDir, tsFile), `${out.trimEnd()}\n`);
}
console.log(counts.join("\n"));
