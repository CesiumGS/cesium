// One-off developer tool: extracts DELTET/DELTA_AT from a NAIF leapseconds
// kernel (naif0012.tls) into src/time/leapTable.ts, the table
// `LeapSeconds.builtIn()` uses. Its output is committed; it is not part of
// the build.
//
// Usage: node scripts/leapTable.mjs <path to naif0012.tls>
// (from https://naif.jpl.nasa.gov/pub/naif/generic_kernels/lsk/naif0012.tls)
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const MONTHS = [
  "JAN",
  "FEB",
  "MAR",
  "APR",
  "MAY",
  "JUN",
  "JUL",
  "AUG",
  "SEP",
  "OCT",
  "NOV",
  "DEC",
];

const lskPath = process.argv[2];
if (!lskPath) {
  console.error("usage: node scripts/leapTable.mjs <naif0012.tls>");
  process.exit(1);
}
const bytes = readFileSync(lskPath);
const text = bytes.toString("latin1");

// Only `\begindata` blocks are data; the rest of an LSK is commentary.
const data = text
  .split("\\begindata")
  .slice(1)
  .map((block) => block.split("\\begintext")[0])
  .join("\n");
const assignment = /DELTET\/DELTA_AT\s*=\s*\(([^)]*)\)/.exec(data);
if (!assignment) {
  throw new Error(`${lskPath}: no DELTET/DELTA_AT assignment`);
}
const rows = [];
const pair = /(-?\d+(?:\.\d*)?)\s*,\s*@(\d{4})-([A-Z]{3})-(\d{1,2})/g;
for (const m of assignment[1].matchAll(pair)) {
  const month = MONTHS.indexOf(m[3]);
  if (month < 0) {
    throw new Error(`${lskPath}: bad month ${m[3]}`);
  }
  rows.push([Date.UTC(Number(m[2]), month, Number(m[4])), Number(m[1])]);
}
if (rows.length === 0) {
  throw new Error(`${lskPath}: DELTET/DELTA_AT has no pairs`);
}
for (let i = 1; i < rows.length; i++) {
  if (!(rows[i][0] > rows[i - 1][0])) {
    throw new Error(`${lskPath}: DELTET/DELTA_AT dates are not increasing`);
  }
}

const sha256 = createHash("sha256").update(bytes).digest("hex");
const lines = rows.map(
  ([ms, dat]) =>
    `  [${ms}, ${dat}], // ${new Date(ms).toISOString().slice(0, 10)}`,
);
const out = `// Generated by scripts/leapTable.mjs from NAIF ${basename(lskPath)}
// (DELTET/DELTA_AT), SHA-256 ${sha256}.
// Do not edit; regenerate from a newer LSK instead.

/** TAI-UTC steps: [UTC ms since 1970 from which it applies, TAI-UTC in s]. */
export const LEAP_TABLE: readonly (readonly [number, number])[] = [
${lines.join("\n")}
];
`;
const target = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "time",
  "leapTable.ts",
);
writeFileSync(target, out);
console.log(`wrote ${target} (${rows.length} steps)`);
