export type ApiGroup = (typeof API_GROUPS)[number]["id"];

export interface ApiRow {
  group: ApiGroup;
  /** 1.x names. `Name.member` checks the member against Name's source. */
  old?: readonly string[];
  /** 1.x names matching this pattern are in the row too, for a family. */
  family?: string;
  /** A few words for the family, in place of listing it. */
  familyLabel?: string;
  /** The 2.0 names the row is about. */
  next?: readonly string[];
  /** Words for the 2.0 side, where names alone wouldn't say what's true. */
  nextLabel?: string;
  /** Options, results and other names that go with them. */
  supporting?: readonly string[];
  status: ApiStatus;
  /** For "absent". */
  gap?: ApiGap;
  /** One plain sentence on what changes for someone migrating. */
  note: string;
  /** Where a plan or spec says so. */
  source?: string;
  /** Not landed: under way, so it doesn't count as true yet. */
  inFlight?: string;
  /** The task in the side-by-side snippets, by id. */
  snippet?: string;
}

