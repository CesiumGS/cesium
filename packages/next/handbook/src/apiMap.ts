/**
 * The 1.x to 2.0 comparison, by hand: plain data with no imports. Names are
 * checked by test/handbookData.test.ts against 1.x's source and
 * api/surface.txt: a 2.0 name here must exist, every exported 2.0 name must
 * be in a row, and a 1.x name must exist. Each claim was checked against the
 * code on the date in DESIGN.md. In a note, `backticks` are code.
 *
 * A 2.0 name is written as it is in api/surface.txt: its name, or
 * `entry:name` outside the core entry point.
 */
export type ApiStatus =
  "same" | "renamed" | "changed" | "covered" | "absent" | "new";

/** Why a 1.x feature isn't in 2.0. */
export type ApiGap =
  /** The plan chooses not to have it. */
  | "design"
  /** Not built: a plan or spec leaves it for later, or says how it would go in. */
  | "later"
  /** Not built, and no plan or spec says what happens to it. */
  | "unknown";

